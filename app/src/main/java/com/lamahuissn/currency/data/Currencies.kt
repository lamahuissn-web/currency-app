package com.lamahuissn.currency.data

/**
 * The catalogue the app lists: ISO code, English name, symbol and the flag of the country the
 * currency belongs to. Generated once from the mledoze/countries dataset and committed as source,
 * so the list itself never needs the network.
 */
data class Currency(
    val code: String,
    val name: String,
    val symbol: String,
    val flag: String,
    val country: String,
    val region: String,
) {
    /** Letter the add-currency list files this row under. */
    val initial: Char get() = name.firstOrNull()?.uppercaseChar() ?: '#'

    /** What the search box matches: name, code, country or region. */
    fun matches(query: String): Boolean {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return true
        return name.lowercase().contains(q) ||
            code.lowercase().contains(q) ||
            country.lowercase().contains(q) ||
            region.lowercase().contains(q)
    }
}

